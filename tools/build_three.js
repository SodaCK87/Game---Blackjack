// 把 node_modules/three 的 ES module 打包成 classic script（全域 THREE），輸出 app/lib/three.js。
// 要打包是因為 file:// 下 ES module 會被 CORS 擋（2026-10-22 Edge／Chrome 實測），而 three 已不再附 UMD 版。
// 用法：npm run build:three（升級 three 時改 package.json 的版本、npm install、再跑這支）
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'app', 'lib', 'three.js');
const THREE_DIR = path.join(ROOT, 'node_modules', 'three');

function build(outfile) {
  const version = JSON.parse(fs.readFileSync(path.join(THREE_DIR, 'package.json'), 'utf8')).version;
  // MIT 授權要求散布時附上版權與授權全文，壓縮會拿掉原本的 @license 註解，所以整份 LICENSE 放進檔頭
  const license = fs.readFileSync(path.join(THREE_DIR, 'LICENSE'), 'utf8').trim();
  esbuild.buildSync({
    stdin: { contents: "export * from 'three';", resolveDir: ROOT },
    bundle: true,
    format: 'iife',
    globalName: 'THREE',
    minify: true,
    legalComments: 'none',
    banner: { js: `/*! three ${version} (IIFE, global THREE). Generated by tools/build_three.js - do not edit.\n\n${license}\n*/` },
    outfile,
    logLevel: 'error',
  });
  return version;
}

module.exports = { build, OUT, THREE_DIR };

if (require.main === module) {
  const version = build(OUT);
  console.log(`app/lib/three.js ← three ${version}（${fs.statSync(OUT).size.toLocaleString()} bytes）`);
}
